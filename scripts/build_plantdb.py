def W(start: int, end: int, anchor: str = "last_frost") -> dict[str, Any]:
    return {"start_week": start, "end_week": end, "anchor": anchor}


def FF(start: int, end: int) -> dict[str, Any]:
    return W(start, end, "first_frost")


def note(en: str, nl: str) -> dict[str, str]:
    return {"en": en, "nl": nl}


def care(task: str, start: int, interval: int | None = None, end: int | None = None, anchor: str = "planting",
         minutes: int = 10, en: str = "", nl: str = "") -> dict[str, Any]:  # fmt: skip
    rule: dict[str, Any] = {"task": task, "start_day": start, "anchor": anchor, "minutes": minutes}
    if interval:
        rule["interval_days"] = interval
    if end is not None:
        rule["end_day"] = end
    if en:
        rule["notes"] = note(en, nl)
    return rule


